                    <h2>4 Steps to Access Your Router Admin Page (192.168.1.1 / 192.168.0.1)</h2>

                    <ol>
                        <li>Connect your device (phone, laptop, or PC) to your router's Wi-Fi network.</li>
                        <li>Open your web browser (Chrome, Edge, or Firefox) and type <code>http://192.168.1.1</code> or <code>http://192.168.0.1</code> into the address bar.</li>
