                        <h1>Modem vs ONT vs Router Explained — What Each Device Does</h1>
                        <p>People often say "router" for every box with lights. In a modern fiber home, there are usually two jobs — and sometimes two devices. Here is the difference between a <strong>modem</strong>, an <strong>ONT</strong>, and a <strong>router</strong>.</p>
                        <h2>Modem / ONT — Brings Internet In</h2>
                        <p>On older copper lines, a <strong>modem</strong> converts the ISP signal into internet. On FTTH fiber, that role is done by an <strong>ONT (Optical Network Terminal)</strong>. It takes light from the fiber cable and converts it into a usable network connection.</p>
                        <div class="info-box"><strong>Remember:</strong> ONT = fiber entry point. No ONT link (often a red LOS light) means no internet, even if WiFi looks on. See our <a href="/blog/router-lights-meaning-troubleshooting">router lights guide</a>.</div>
                        <h2>Router — Shares Internet Around the Home</h2>
                        <p>The <strong>router</strong> takes the single internet connection and shares it with all your devices over WiFi and ethernet. It also assigns local IPs, creates your WiFi name/password, and manages traffic.</p>
                        <h2>Quick Comparison</h2>
                        <table>
                            <thead><tr><th>Device</th><th>Job</th><th>Typical for</th></tr></thead>
                            <tbody>
                                <tr><td>Modem</td><td>ISP signal → internet</td><td>DSL / cable</td></tr>
                                <tr><td class="nisan-col">ONT</td><td>Fiber light → internet</td><td>FTTH fiber</td></tr>
                                <tr><td class="nisan-col">Router</td><td>Shares WiFi / LAN</td><td>Every home</td></tr>
                            </tbody>
                        </table>
                        <div class="verdict-box"><strong>Bottom line:</strong> ONT brings fiber in; router makes WiFi work. If internet is down, check ONT lights first. If only one room is weak, it is usually WiFi/router placement — not the ONT.</div>
