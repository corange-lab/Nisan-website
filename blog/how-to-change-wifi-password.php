<div itemscope itemtype="https://schema.org/FAQPage">
<h3>How do I change my WiFi password?</h3>
<p>Log into your router admin page (usually 192.168.0.1 or 192.168.1.1), open Wireless/WiFi settings, set a new WPA2/WPA3 password, and save. Reconnect all devices with the new password.</p>
<h3>Will changing WiFi password disconnect devices?</h3>
<p>Yes. All devices must reconnect using the new password. That is also how you kick unknown users off your network.</p>
<h3>What is a strong WiFi password?</h3>
<p>Use 12+ characters with letters, numbers and symbols. Avoid names, phone numbers and simple sequences.</p>
<h3>I forgot the router admin password. What now?</h3>
<p>Check the sticker on the router for defaults, or ask your ISP/technician. A factory reset works but erases custom settings.</p>
